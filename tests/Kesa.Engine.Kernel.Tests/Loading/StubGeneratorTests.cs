using System;
using Kesa.Engine.Loading;
using Kesa.Engine.Stubs;
using NUnit.Framework;

namespace Kesa.Engine.Tests.Loading
{
    /// <summary>작성용 .pyi 스텁 (spec-gaps G71·G72).</summary>
    public class StubGeneratorTests : LoaderTestBase
    {
        private const string Schema =
            "def hmax(h: Health) -> int:\n    return h.base_max\n" +
            "component(\"Health\", base_max=const(int, default=10), max=derived(int, hmax), current=field(int, default=5))\n" +
            "deftype(\"Resource\")\n" +
            "component(\"Skill\", key=\"Resource\", level=const(int, default=1))\n" +
            "deftype(\"Unit\",\n" +
            "    components=[\"Health\", \"Skill\"],\n" +
            "    move=const(int, default=1),\n" +
            "    ratio=const(fixed, default=1.5),\n" +
            "    label=const(TextKey, default=\"\"),\n" +
            "    tags=const(list[str]),\n" +
            "    cost=const(dict[DefId[\"Resource\"], int]),\n" +
            ")\n";

        private const string Defs =
            "Resource(\"Wood\")\nResource(\"Iron\")\n" +
            "Unit(\"Base\", abstract=True)\n" +
            "Unit(\"Scout\", parent=\"Base\")\n";

        private string StubFor(string mod, ContentLoadResult result) => StubGenerator.Generate(mod, result);

        [Test]
        public void ProducesTheDeclarationsOfTheMod()
        {
            Mod("core", schema: Schema, defs: Defs);
            var stub = StubFor("core", LoadClean());

            const string expected =
                "# generated by the engine for mod 'core'. Do not edit. Needs pythonVersion 3.12 or later.\n" +
                "from typing import Any, Callable, Literal, Never\n" +
                "\n" +
                "type fixed = int | float\n" +
                "type TextKey = str\n" +
                "\n" +
                "class Health:\n" +
                "    def __init__(self, *, base_max: int = ..., current: int = ...) -> None: ...\n" +
                "\n" +
                "class Skill:\n" +
                "    def __init__(self, *, level: int = ...) -> None: ...\n" +
                "\n" +
                "class Resource:\n" +
                "    def __init__(self, id: str, *, parent: Literal[\"Wood\", \"Iron\"] | None = None, abstract: bool = False, " +
                "override: bool = False) -> None: ...\n" +
                "\n" +
                "class Unit:\n" +
                "    def __init__(self, id: str, *, parent: Literal[\"Base\", \"Scout\"] | None = None, abstract: bool = False, " +
                "override: bool = False, move: int = ..., ratio: fixed = ..., label: TextKey = ..., tags: list[str] = ..., " +
                "cost: dict[Literal[\"Wood\", \"Iron\"], int] = ..., Health: Health = ..., " +
                "Skill: dict[Literal[\"Wood\", \"Iron\"], Skill] = ...) -> None: ...\n" +
                "\n" +
                "class patch:\n" +
                "    @staticmethod\n" +
                "    def set(def_id: Literal[\"Wood\", \"Iron\", \"Base\", \"Scout\"], path: str, value: Any) -> None: ...\n" +
                "    @staticmethod\n" +
                "    def add(def_id: Literal[\"Wood\", \"Iron\", \"Base\", \"Scout\"], path: str, value: Any) -> None: ...\n" +
                "    @staticmethod\n" +
                "    def append(def_id: Literal[\"Wood\", \"Iron\", \"Base\", \"Scout\"], path: str, value: Any) -> None: ...\n" +
                "    @staticmethod\n" +
                "    def remove(def_id: Literal[\"Wood\", \"Iron\", \"Base\", \"Scout\"], path: str, value: Any = ...) -> None: ...\n" +
                "\n" +
                "def mod_loaded(mod: Never) -> bool: ...\n" +
                "\n" +
                "inherit: Any\n";
            Assert.That(stub, Is.EqualTo(expected));
        }

        [Test]
        public void TheSameLoadGivesTheSameText()
        {
            Mod("core", schema: Schema, defs: Defs);
            var result = LoadClean();
            Assert.That(StubFor("core", result), Is.EqualTo(StubFor("core", result)));
        }

        [Test]
        public void AbstractDefsAreLeftOutOfDefIdLiteralsButStayValidParents()
        {
            Mod("core", schema: Schema, defs: Defs + "Unit(\"Tower\", abstract=True)\n");
            var stub = StubFor("core", LoadClean());
            Assert.That(stub, Does.Contain("parent: Literal[\"Base\", \"Scout\", \"Tower\"] | None"));
            Assert.That(stub, Does.Not.Contain("Literal[\"Wood\", \"Iron\", \"Base\"]"));
        }

        [Test]
        public void AModOnlySeesWhatItsDependenciesProvide()
        {
            Mod("core", schema: Schema, defs: Defs);
            Mod("farm", schema: "component(\"Crop\", yield_per=const(int, default=1))\nextend(\"Unit\", farmer=const(bool, default=False))\n",
                defs: "Resource(\"Grain\")\n", extra: ", dependencies=[\"core\"]");
            Mod("addon", defs: "Unit(\"Peasant\")\n", extra: ", dependencies=[\"core\"], optional=[\"farm\"]");
            var result = LoadClean();

            var core = StubFor("core", result);
            Assert.That(core, Does.Not.Contain("Crop").And.Not.Contain("farmer").And.Not.Contain("Grain").And.Not.Contain("Peasant"));

            var farm = StubFor("farm", result);
            Assert.That(farm, Does.Contain("class Crop:").And.Contain("farmer: bool = ...").And.Contain("\"Grain\""));
            Assert.That(farm, Does.Not.Contain("Peasant"));

            // addon은 farm에 의존하지 않고 optional이라 farm의 것은 보이지 않지만, mod_loaded에서 이름은 쓸 수 있다
            var addon = StubFor("addon", result);
            Assert.That(addon, Does.Not.Contain("Crop").And.Not.Contain("Grain").And.Not.Contain("farmer"));
            Assert.That(addon, Does.Contain("def mod_loaded(mod: Literal[\"core\", \"farm\"]) -> bool: ..."));
            Assert.That(addon, Does.Contain("\"Peasant\""));
        }

        [Test]
        public void FunctionSlotsAndEntityKeyedComponentsAreHandled()
        {
            Mod("core",
                schema:
                "def always(g: Goal) -> bool:\n    return True\n" +
                "component(\"Owner\", key=Ref[\"Faction\"], share=field(int, default=0))\n" +
                "component(\"Treasury\", gold=field(int, default=0))\n" +
                "deftype(\"Faction\", components=[\"Treasury\"])\n" +
                "deftype(\"Goal\", ok=const(Cond[\"Goal\"]), then=const(list[Action[\"Goal\"]], merge=\"append\"), components=[\"Owner\"])\n",
                defs: "def yes(g: Goal) -> bool:\n    return True\nGoal(\"G\", ok=yes)\n");
            var stub = StubFor("core", LoadClean());
            Assert.That(stub, Does.Contain("ok: Callable[..., bool] = ..."));
            Assert.That(stub, Does.Contain("then: list[Callable[..., None]] = ..."));
            Assert.That(stub, Does.Not.Contain("Owner: "));
        }

        [Test]
        public void IdsWithQuotesAndBackslashesAreEscaped()
        {
            Mod("core", schema: "deftype(\"Resource\")\n", defs: "Resource(\"a\\\"b\")\n");
            Assert.That(StubFor("core", LoadClean()), Does.Contain("Literal[\"a\\\"b\"]"));
        }

        [Test]
        public void ADisabledOrUnknownModHasNoStub()
        {
            Mod("core", schema: Schema, defs: Defs);
            var result = LoadClean();
            Assert.Throws<ArgumentException>(() => StubFor("nope", result));
        }
    }
}
