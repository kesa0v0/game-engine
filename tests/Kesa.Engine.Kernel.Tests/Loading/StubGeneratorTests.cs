        /// <summary>
        /// 모드의 스키마 스텁은 그 모드가 보는 클래스를 더해 <c>derived</c> 함수의 <c>def hmax(h: Health)</c>를 받는다 (G209).
        /// 스키마 파일에서 <c>fixed</c>·<c>TextKey</c>는 값이므로 클래스 안의 타입 자리에는 풀어 쓴다.
