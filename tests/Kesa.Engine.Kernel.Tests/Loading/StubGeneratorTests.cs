        [Test]
        public void AVisibleComponentOrSignalReplacesTheBuiltinOfTheSameName()
        {
            // 보이는 스키마 이름이 내장을 이긴다 (G230): 내장 선언을 빼서 이름이 두 번 선언되지 않는다
