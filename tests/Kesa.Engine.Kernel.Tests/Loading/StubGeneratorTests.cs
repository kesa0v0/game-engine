        /// <summary>
        /// 스크립트가 쓸 수 있는 엔진 이름은 모두 스텁에 있다 (G207): 새 내장을 더하고 스텁을 잊으면 여기서 걸린다.
        /// 파이썬 내장과 같은 이름(<c>len</c> 등)은 pyright가 이미 안다.
        /// </summary>
        [Test]
        public void EveryNameScriptsCanUseIsDeclared()
        {
            Mod("core", schema: Schema, defs: Defs);
            var stub = StubFor("core", LoadClean());
            var schemaStub = StubGenerator.GenerateSchema();
            var python = new[] { "abs", "all", "any", "len", "max", "min", "range", "round", "sum" };
            bool Declares(string text, string name) =>
                text.Contains("\ndef " + name + "(") || text.Contains("\ndef " + name + "[") || text.Contains("\nclass " + name + ":") ||
                text.Contains("\n" + name + ": ") || text.Contains("\ntype " + name + "[");
            foreach (var name in Kesa.Engine.Script.PureBuiltins.RuntimeNames)
                if (System.Array.IndexOf(python, name) < 0)
                    Assert.That(Declares(stub, name), Is.True, name + " is missing from the mod stub");
            foreach (var name in new[]
                     {
                         Kesa.Engine.Script.Interpreter.CommandName,
                         Kesa.Engine.Script.Interpreter.ViewPolicyName, Kesa.Engine.Script.Interpreter.OnName,
                         Kesa.Engine.Script.Interpreter.WhenName, "preconditions", "require", "cost", "choose", "Ref", "DefId",
                     })
                Assert.That(Declares(stub, name), Is.True, name + " is missing from the mod stub");
            // derived 함수(스키마 파일)가 쓰는 순수 내장
            foreach (var name in new[] { "floor", "ceil", "clamp", "contribs", "now", "query", "text" })
                Assert.That(Declares(schemaStub, name), Is.True, name + " is missing from the schema stub");
        }

