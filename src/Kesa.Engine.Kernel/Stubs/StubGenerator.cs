using System;
using System.Collections.Generic;
using System.Text;
using Kesa.Engine.Loading;
using Kesa.Engine.Schema;

namespace Kesa.Engine.Stubs
{
    /// <summary>
    /// 작성용 <c>.pyi</c> 스텁 생성기 (spec S1 ⑥, spec-gaps G71·G72). 한 모드가 Def·패치 파일을 쓸 때 편집기가 쓰는 선언을 만든다:
    /// 그 모드가 볼 수 있는 범위(자기 + 필수 의존의 닫힘)의 Def 타입 클래스, 컴포넌트 값 클래스, <c>Literal</c> Def id,
    /// <c>patch</c>, <c>mod_loaded</c>, <c>inherit</c>. 로직용(엔티티 접근, <c>derived</c>, <c>ref</c> 칼럼)은 로직 슬라이스에서 더한다.
    /// 파일로 쓰는 일은 하지 않는다: 같은 입력이면 같은 문자열이다.
    /// </summary>
    public static class StubGenerator
    {
        public static string Generate(string modId, ContentLoadResult result)
        {
            ModManifest? manifest = null;
            foreach (var m in result.Mods)
                if (m.Id == modId) manifest = m;
            if (manifest == null) throw new ArgumentException("mod '" + modId + "' is not loaded", nameof(modId));
            return new Writer(manifest, result).Write();
        }

        private sealed class Writer
        {
            private readonly ModManifest _mod;
            private readonly ContentLoadResult _result;
            private readonly ModVisibility _visibility;
            private readonly StringBuilder _out = new StringBuilder();

            public Writer(ModManifest mod, ContentLoadResult result)
            {
                _mod = mod;
                _result = result;
                _visibility = new ModVisibility(result.Mods);
            }

            private bool Sees(string owner) => _visibility.CanSee(_mod.Id, owner);

            private void Line(string text = "") => _out.Append(text).Append('\n');

            public string Write()
            {
                Line("# generated by the engine for mod '" + _mod.Id + "'. Do not edit. Needs pythonVersion 3.12 or later.");
                Line("from typing import Any, Callable, Literal, Never");
                Line();
                Line("type fixed = int | float");
                Line("type TextKey = str");
                Line();

                foreach (var c in _result.Schema.Components)
                    if (Sees(c.Mod)) WriteComponent(c);
                foreach (var t in _result.Schema.Types)
                    if (Sees(t.Mod)) WriteDefType(t);

                WritePatch();
                WriteModLoaded();
                Line("inherit: Any");
                return _out.ToString();
            }

            // ---- 컴포넌트와 Def 타입 ----

            private void WriteComponent(ComponentType component)
            {
                Line("class " + component.Name + ":");
                var parameters = new List<string>();
                foreach (var member in component.Members)
                {
                    if (member.Kind == MemberKind.Derived || member.Kind == MemberKind.Ref) continue;
                    parameters.Add(member.Name + ": " + TypeText(member.Spec.Type) + " = ...");
                }
                WriteInit(parameters, keywordOnly: true);
                Line();
            }

            private void WriteDefType(DefType type)
            {
                Line("class " + type.Name + ":");
                var parameters = new List<string>
                {
                    "id: str",
                    "*",
                    "parent: " + ParentText(type) + " = None",
                    "abstract: bool = False",
                    "override: bool = False",
                };
                foreach (var k in type.Consts)
                    if (Sees(k.Mod)) parameters.Add(k.Name + ": " + TypeText(k.Spec.Type) + " = ...");
                foreach (var slot in type.Components)
                {
                    if (!Sees(slot.Mod)) continue;
                    var component = slot.Component;
                    if (component.IsKeyed)
                    {
                        // 엔티티가 키인 컴포넌트의 줄은 런타임에만 생기므로 Def에 쓸 수 없다
                        if (component.KeyKind != KeyKind.Def || component.Key == null) continue;
                        parameters.Add(component.Name + ": dict[" + DefIdLiteral(component.Key.Name) + ", " + component.Name +
                                       "] = ...");
                    }
                    else
                    {
                        parameters.Add(component.Name + ": " + component.Name + " = ...");
                    }
                }
                WriteInit(parameters, keywordOnly: false);
                Line();
            }

            private void WriteInit(List<string> parameters, bool keywordOnly)
            {
                var all = new List<string> { "self" };
                if (keywordOnly && parameters.Count > 0) all.Add("*");
                all.AddRange(parameters);
                Line("    def __init__(" + string.Join(", ", all) + ") -> None: ...");
            }

            private string ParentText(DefType type)
            {
                var ids = new List<string>();
                foreach (var d in _result.Defs.Defs)
                    if (d.Type == type && VisibleDef(d)) ids.Add(d.Id);
                return ids.Count == 0 ? "None" : Literal(ids) + " | None";
            }

            // ---- 타입 표기 ----

            private string TypeText(TypeRef type)
            {
                switch (type)
                {
                    case PrimitiveTypeRef p:
                        return p.Name;
                    case ListTypeRef list:
                        return "list[" + TypeText(list.Element) + "]";
                    case DictTypeRef dict:
                        return "dict[" + TypeText(dict.Key) + ", " + TypeText(dict.Value) + "]";
                    case DefIdTypeRef id:
                        return DefIdLiteral(id.Target.Name);
                    case FunctionTypeRef f:
                        return f.Kind == FunctionSlotKind.Cond ? "Callable[..., bool]" : "Callable[..., None]";
                }
                return "Any";
            }

            /// <summary>보이는 <b>구체</b> Def의 id (abstract는 가리킬 수 없다, G66).</summary>
            private string DefIdLiteral(string typeName)
            {
                var ids = new List<string>();
                foreach (var d in _result.Defs.Defs)
                    if (d.Type.Name == typeName && !d.IsAbstract && VisibleDef(d)) ids.Add(d.Id);
                return ids.Count == 0 ? "Never" : Literal(ids);
            }

            private bool VisibleDef(DefRecord record)
            {
                for (var r = record; r != null; r = r.Replaced)
                    if (Sees(r.Mod)) return true;
                return false;
            }

            private static string Literal(List<string> values)
            {
                var parts = new List<string>();
                foreach (var v in values) parts.Add(Quote(v));
                return "Literal[" + string.Join(", ", parts) + "]";
            }

            private static string Quote(string text) =>
                "\"" + text.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

            // ---- patch, mod_loaded ----

            private void WritePatch()
            {
                var ids = new List<string>();
                foreach (var d in _result.Defs.Defs)
                    if (VisibleDef(d)) ids.Add(d.Id);
                string target = ids.Count == 0 ? "str" : Literal(ids);

                Line("class patch:");
                foreach (var op in new[] { "set", "add", "append" })
                {
                    Line("    @staticmethod");
                    Line("    def " + op + "(def_id: " + target + ", path: str, value: Any) -> None: ...");
                }
                Line("    @staticmethod");
                Line("    def remove(def_id: " + target + ", path: str, value: Any = ...) -> None: ...");
                Line();
            }

            private void WriteModLoaded()
            {
                var ids = new List<string>();
                foreach (var d in _mod.Dependencies) ids.Add(d.Id);
                foreach (var o in _mod.Optional) ids.Add(o.Id);
                ids.Sort(StringComparer.Ordinal);
                string arg = ids.Count == 0 ? "Never" : Literal(ids);
                Line("def mod_loaded(mod: " + arg + ") -> bool: ...");
                Line();
            }
        }
    }
}
