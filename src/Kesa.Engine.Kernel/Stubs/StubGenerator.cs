        /// <summary>
        /// 로드된 모드는 최종 결과로 만든다. ③~⑥에서 비활성화된 모드는 첫 회차 결과(<see cref="ContentLoadResult.FirstRound"/>)로
        /// 만들고 머리에 그렇다고 적는다 (spec-gaps G83). 둘 다 없으면(②까지 실패) <see cref="CanGenerate"/>가 거짓이다.
        /// </summary>
        public static string Generate(string modId, ContentLoadResult result) =>
            (WriterFor(modId, result) ??
             throw new ArgumentException("mod '" + modId + "' did not get through its schema and Def files", nameof(modId))).Write();

        /// <summary>
        /// 한 모드의 스키마 파일용 스텁 (spec-gaps G209): 모드와 무관한 <see cref="GenerateSchema()"/>에 그 모드가 보는 컴포넌트·Def 타입
        /// 클래스를 더한다. <c>derived</c> 함수의 <c>def hmax(h: Health)</c>가 통과하고 <c>h.base_max</c>를 검사한다.
        /// ②에서 실패해 선언을 모르면 모드와 무관한 것만 준다.
        /// </summary>
        public static string GenerateSchema(string modId, ContentLoadResult result)
        {
            var writer = WriterFor(modId, result);
            if (writer == null) return GenerateSchema();
            writer.ForSchemaFiles = true;
            return GenerateSchema() + "\n# the classes mod '" + modId + "' can see, for type hints such as def f(h: Health)\n" +
                   writer.WriteClasses();
        }

        private static Writer? WriterFor(string modId, ContentLoadResult result)
        {
            var final = Find(modId, result.Mods);
            if (final != null) return new Writer(final, result.Mods, result.Schema, result.Defs, fromFirstRound: false);
            var first = Find(modId, result.FirstRound.Mods);
            if (first != null)
                return new Writer(first, result.FirstRound.Mods, result.FirstRound.Schema, result.FirstRound.Defs, fromFirstRound: true);
            return null;
        }

        /// <summary>최종 결과나 첫 회차 결과에 이 모드가 있는가.</summary>
        public static bool CanGenerate(string modId, ContentLoadResult result) =>
            Find(modId, result.Mods) != null || Find(modId, result.FirstRound.Mods) != null;

