using System;
using System.Collections.Generic;
using System.Text;
using Kesa.Engine.Loading;
using Kesa.Engine.Schema;

namespace Kesa.Engine.Stubs
{
    /// <summary>
    /// 작성용 <c>.pyi</c> 스텁 생성기 (spec S1 ⑥, spec-gaps G71·G72). 한 모드가 Def·패치 파일을 쓸 때 편집기가 쓰는 선언을 만든다:
    /// 그 모드가 볼 수 있는 범위(자기 + 필수 의존의 닫힘)의 Def 타입 클래스, 컴포넌트 값 클래스, <c>Literal</c> Def id,
    /// <c>patch</c>, <c>mod_loaded</c>, <c>inherit</c>. 로직용(엔티티 접근, <c>derived</c>, <c>ref</c> 칼럼)은 로직 슬라이스에서 더한다.
    /// 파일로 쓰는 일은 하지 않는다: 같은 입력이면 같은 문자열이다.
    /// </summary>
    public static class StubGenerator
    {
        /// <summary>
        /// 로드된 모드는 최종 결과로 만든다. ③~⑥에서 비활성화된 모드는 첫 회차 결과(<see cref="ContentLoadResult.FirstRound"/>)로
        /// 만들고 머리에 그렇다고 적는다 (spec-gaps G83). 둘 다 없으면(②까지 실패) <see cref="CanGenerate"/>가 거짓이다.
        /// </summary>
        public static string Generate(string modId, ContentLoadResult result)
        {
            var final = Find(modId, result.Mods);
            if (final != null)
                return new Writer(final, result.Mods, result.Schema, result.Defs, fromFirstRound: false).Write();
            var first = Find(modId, result.FirstRound.Mods);
            if (first != null)
                return new Writer(first, result.FirstRound.Mods, result.FirstRound.Schema, result.FirstRound.Defs,
                    fromFirstRound: true).Write();
            throw new ArgumentException("mod '" + modId + "' did not get through its schema and Def files", nameof(modId));
        }

        /// <summary>최종 결과나 첫 회차 결과에 이 모드가 있는가.</summary>
        public static bool CanGenerate(string modId, ContentLoadResult result) =>
            Find(modId, result.Mods) != null || Find(modId, result.FirstRound.Mods) != null;

        /// <summary>
        /// 스키마·Def 파일 단계(②)에서 실패해 Def 선언을 알 수 없는 모드의 최소 스텁: 매니페스트 이름만 (G83).
        /// <c>mod.py</c>가 거짓 오류를 내지 않게 한다.
        /// </summary>
        public static string GenerateManifestOnly(string modId) =>
            "# generated by the engine for mod '" + modId + "'. Do not edit. Needs pythonVersion 3.12 or later.\n" +
            "# the mod failed to load (see engine check), so only the mod.py names are declared.\n" +
            ManifestNames;

        private const string ManifestNames =
            "def Mod(*, id: str, version: str = ..., defaultLanguage: str = ..., dependencies: list[str] = ..., " +
            "loadAfter: list[str] = ..., optional: list[str] = ...) -> None: ...\n" +
            "def use(path: str, /) -> None: ...\n" +
            "def use_all(path: str, /) -> None: ...\n";

        private static ModManifest? Find(string modId, IReadOnlyList<ModManifest> mods)
        {
            foreach (var m in mods)
                if (m.Id == modId) return m;
            return null;
        }

        /// <summary>
        /// 스키마 파일(<c>schema/</c> 아래)용 스텁 (spec-gaps G82). 스키마 안의 이름은 문자열이라 모드와 무관하게 같다.
        /// 타입 자리는 느슨하게 <c>Any</c>로 두고, 멤버 선언은 불투명한 <c>MemberDecl</c>로 받아 <c>const(...)</c>를 빠뜨린 멤버를 잡는다.
        /// </summary>
        public static string GenerateSchema() =>
            "# generated by the engine for schema files. Do not edit. Needs pythonVersion 3.12 or later.\n" +
            "from typing import Any, Callable, Literal\n" +
            "\n" +
            "class MemberDecl: ...\n" +
            "\n" +
            "fixed: Any\n" +
            "TextKey: Any\n" +
            "Ref: Any\n" +
            "DefId: Any\n" +
            "Cond: Any\n" +
            "Action: Any\n" +
            "\n" +
            "def deftype(name: str, /, *, components: list[str] = ..., **consts: MemberDecl) -> None: ...\n" +
            "def component(name: str, /, *, key: Any = ..., keys: Literal[\"all\", \"listed\"] = ..., **members: MemberDecl) -> None: ...\n" +
            "def extend(type_name: str, /, *, components: list[str] = ..., **consts: MemberDecl) -> None: ...\n" +
            "def signal(name: str, /, **values: Any) -> None: ...\n" +
            "def stage(id: str, /, *, after: list[str] = ..., before: list[str] = ..., optional_after: list[str] = ..., " +
            "optional_before: list[str] = ...) -> None: ...\n" +
            "def const(type: Any, /, *, default: Any = ..., min: int | float = ..., max: int | float = ..., " +
            "merge: Literal[\"replace\", \"append\"] = ...) -> MemberDecl: ...\n" +
            "def field(type: Any, /, *, default: Any = ..., default_from: str = ..., min: int | float = ..., " +
            "max: int | float = ...) -> MemberDecl: ...\n" +
            "def derived(type: Any, fn: Callable[..., Any], /) -> MemberDecl: ...\n" +
            "def ref(type_name: str, /, *, inverse: str = ..., optional: bool = ..., order_by: str = ...) -> MemberDecl: ...\n";

        private sealed class Writer
        {
            private readonly ModManifest _mod;
            private readonly SchemaSet _schema;
            private readonly DefRegistry _defs;
            private readonly bool _fromFirstRound;
            private readonly ModVisibility _visibility;
            private readonly StringBuilder _out = new StringBuilder();

            public Writer(ModManifest mod, IReadOnlyList<ModManifest> mods, SchemaSet schema, DefRegistry defs,
                bool fromFirstRound)
            {
                _mod = mod;
                _schema = schema;
                _defs = defs;
                _fromFirstRound = fromFirstRound;
                _visibility = new ModVisibility(mods);
            }

            private bool Sees(string owner) => _visibility.CanSee(_mod.Id, owner);

            private void Line(string text = "") => _out.Append(text).Append('\n');

            public string Write()
            {
                Line("# generated by the engine for mod '" + _mod.Id + "'. Do not edit. Needs pythonVersion 3.12 or later.");
                if (_fromFirstRound)
                    Line("# the mod failed to load (see engine check); these declarations come from before it was disabled.");
                Line("from typing import Any, Callable, Literal, Never");
                Line();
                Line("type fixed = int | float");
                Line("type TextKey = str");
                Line();

                foreach (var c in _schema.Components)
                    if (Sees(c.Mod)) WriteComponent(c);
                foreach (var t in _schema.Types)
                    if (Sees(t.Mod)) WriteDefType(t);
                foreach (var s in _schema.Signals)
                    if (Sees(s.Mod)) WriteSignal(s);

                WritePatch();
                WriteModLoaded();
                Line("inherit: Any");
                Line();
                // mod.py는 모드 폴더 바로 아래라 이 스텁을 같이 쓴다 (spec-gaps G82)
                _out.Append(ManifestNames);
                return _out.ToString();
            }

            // ---- 컴포넌트와 Def 타입 ----

            private void WriteComponent(ComponentType component)
            {
                Line("class " + component.Name + ":");
                var parameters = new List<string>();
                foreach (var member in component.Members)
                {
                    if (member.Kind == MemberKind.Derived || member.Kind == MemberKind.Ref) continue;
                    parameters.Add(member.Name + ": " + TypeText(member.Spec.Type) + " = ...");
                }
                WriteInit(parameters, keywordOnly: true);
                Line();
            }

            /// <summary>신호 (spec-gaps G145): 인자는 모두 필수인 키워드 인자이고 <c>d.amount</c>로 읽는다.</summary>
            private void WriteSignal(SignalType signal)
            {
                Line("class " + signal.Name + ":");
                var parameters = new List<string>();
                foreach (var field in signal.Fields)
                {
                    Line("    " + field.Name + ": " + TypeText(field.Type));
                    parameters.Add(field.Name + ": " + TypeText(field.Type));
                }
                WriteInit(parameters, keywordOnly: true);
                Line();
            }

            private void WriteDefType(DefType type)
            {
                Line("class " + type.Name + ":");
                var parameters = new List<string>
                {
                    "id: str",
                    "*",
                    "parent: " + ParentText(type) + " = None",
                    "abstract: bool = False",
                    "override: bool = False",
                };
                foreach (var k in type.Consts)
                    if (Sees(k.Mod)) parameters.Add(k.Name + ": " + TypeText(k.Spec.Type) + " = ...");
                foreach (var slot in type.Components)
                {
                    if (!Sees(slot.Mod)) continue;
                    var component = slot.Component;
                    if (component.IsKeyed)
                    {
                        // 엔티티가 키인 컴포넌트의 줄은 런타임에만 생기므로 Def에 쓸 수 없다
                        if (component.KeyKind != KeyKind.Def || component.Key == null) continue;
                        parameters.Add(component.Name + ": dict[" + DefIdLiteral(component.Key.Name) + ", " + component.Name +
                                       "] = ...");
                    }
                    else
                    {
                        parameters.Add(component.Name + ": " + component.Name + " = ...");
                    }
                }
                WriteInit(parameters, keywordOnly: false);
                Line();
            }

            private void WriteInit(List<string> parameters, bool keywordOnly)
            {
                var all = new List<string> { "self" };
                if (keywordOnly && parameters.Count > 0) all.Add("*");
                all.AddRange(parameters);
                Line("    def __init__(" + string.Join(", ", all) + ") -> None: ...");
            }

            private string ParentText(DefType type)
            {
                var ids = new List<string>();
                foreach (var d in _defs.Defs)
                    if (d.Type == type && VisibleDef(d)) ids.Add(d.Id);
                return ids.Count == 0 ? "None" : Literal(ids) + " | None";
            }

            // ---- 타입 표기 ----

            private string TypeText(TypeRef type)
            {
                switch (type)
                {
                    case PrimitiveTypeRef p:
                        return p.Name;
                    case ListTypeRef list:
                        return "list[" + TypeText(list.Element) + "]";
                    case DictTypeRef dict:
                        return "dict[" + TypeText(dict.Key) + ", " + TypeText(dict.Value) + "]";
                    case DefIdTypeRef id:
                        return DefIdLiteral(id.Target.Name);
                    case FunctionTypeRef f:
                        return f.Kind == FunctionSlotKind.Cond ? "Callable[..., bool]" : "Callable[..., None]";
                }
                return "Any";
            }

            /// <summary>보이는 <b>구체</b> Def의 id (abstract는 가리킬 수 없다, G66).</summary>
            private string DefIdLiteral(string typeName)
            {
                var ids = new List<string>();
                foreach (var d in _defs.Defs)
                    if (d.Type.Name == typeName && !d.IsAbstract && VisibleDef(d)) ids.Add(d.Id);
                return ids.Count == 0 ? "Never" : Literal(ids);
            }

            private bool VisibleDef(DefRecord record)
            {
                for (var r = record; r != null; r = r.Replaced)
                    if (Sees(r.Mod)) return true;
                return false;
            }

            private static string Literal(List<string> values)
            {
                var parts = new List<string>();
                foreach (var v in values) parts.Add(Quote(v));
                return "Literal[" + string.Join(", ", parts) + "]";
            }

            private static string Quote(string text) =>
                "\"" + text.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

            // ---- patch, mod_loaded ----

            private void WritePatch()
            {
                var ids = new List<string>();
                foreach (var d in _defs.Defs)
                    if (VisibleDef(d)) ids.Add(d.Id);
                string target = ids.Count == 0 ? "str" : Literal(ids);

                Line("class patch:");
                foreach (var op in new[] { "set", "add", "append" })
                {
                    Line("    @staticmethod");
                    Line("    def " + op + "(def_id: " + target + ", path: str, value: Any) -> None: ...");
                }
                Line("    @staticmethod");
                Line("    def remove(def_id: " + target + ", path: str, value: Any = ...) -> None: ...");
                Line();
            }

            private void WriteModLoaded()
            {
                var ids = new List<string>();
                foreach (var d in _mod.Dependencies) ids.Add(d.Id);
                foreach (var o in _mod.Optional) ids.Add(o.Id);
                ids.Sort(StringComparer.Ordinal);
                string arg = ids.Count == 0 ? "Never" : Literal(ids);
                Line("def mod_loaded(mod: " + arg + ") -> bool: ...");
                Line();
            }
        }
    }
}
